test('edits metadata and stages a fetched cover until saving; refresh and library cards retain changes', async ({ browser }) => {
  const context = await browser.newContext({ storageState: await storageState(browser, 'user'), colorScheme: 'dark', viewport: { width: 1440, height: 1100 } })
  const page = await context.newPage()
  const prefix = `EditQA${Date.now()}`
  const added = await context.request.post('/api/books/manual', { data: { title: `${prefix} Original`, authors: ['Original Author'], isbn: null, note: 'Private note', rating: 4, tags: ['Favourite'], readingStatus: 'reading', currentPage: 12 } })
  expect(added.ok()).toBe(true)
  const original = await added.json()
  await page.goto(`/library/${original.id}`)
  await page.getByRole('button', { name: 'Edit book', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: 'Edit book', exact: true })
  await dialog.getByLabel('Title', { exact: true }).fill('Unsaved title')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${prefix} Original`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit book', exact: true }).click()
  dialog = page.getByRole('dialog', { name: 'Edit book', exact: true })
  const corrected = `${prefix} Corrected title with a longer subtitle`
  await dialog.getByLabel('Title', { exact: true }).fill(corrected)
  await dialog.getByLabel('Author 1', { exact: true }).fill('Corrected Author')
  await dialog.getByRole('button', { name: 'Add author', exact: true }).click()
  await dialog.getByLabel('Author 2', { exact: true }).fill('Second Author')
  await dialog.getByLabel('ISBN', { exact: true }).fill(fixtureIsbn)
  await dialog.getByLabel('Publisher', { exact: true }).fill('My Publisher')
  await dialog.getByLabel('Description', { exact: true }).fill('My description')
  await dialog.getByRole('button', { name: 'Find missing details by ISBN' }).click()
  await expect(dialog.getByLabel('Publisher', { exact: true })).toHaveValue('My Publisher')
  await expect(dialog.getByLabel('Title', { exact: true })).toHaveValue(corrected)
  await dialog.getByRole('spinbutton', { name: 'Pages', exact: true }).fill('318')
  await page.route('**/cover-preview', route => route.fulfill({ json: { data: png.toString('base64'), size: png.length, contentType: 'image/png' } }))
  await dialog.getByRole('button', { name: 'Find cover by ISBN', exact: true }).click()
  await expect(dialog.getByAltText('Cover preview')).toBeVisible()
  const beforeSave = await (await context.request.get(`/api/books/${original.id}`)).json()
  expect(beforeSave.coverPath).toBeNull()
  const response = page.waitForResponse(r => r.request().method() === 'PUT' && new URL(r.url()).pathname === `/api/books/${original.id}`)
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  expect((await response).ok()).toBe(true)
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('heading', { name: corrected, exact: true })).toBeVisible()
  const saved = await (await context.request.get(`/api/books/${original.id}`)).json()
  expect(saved).toMatchObject({ title: corrected, note: 'Private note', rating: 4, numberOfPages: 318, description: 'My description', publishers: 'My Publisher', readingProgress: { currentPage: 12 } })
  expect(saved.coverPath).toMatch(/^covers\/manual\//)
  expect(saved.authors.map((author: { name: string }) => author.name)).toEqual(['Corrected Author', 'Second Author'])
  await page.reload()
  await expect(page.getByRole('heading', { name: corrected, exact: true })).toBeVisible()

  await page.goto('/library')
  await librarySearchInput(page).fill(corrected)
  await expect(page.getByRole('heading', { name: corrected, exact: true })).toBeVisible()
  await context.close()
})

test('mobile editor supports cover upload and removal without horizontal overflow @mobile', async ({ browser }) => {
  const context = await browser.newContext({ storageState: await storageState(browser, 'user'), viewport: { width: 393, height: 851 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  const added = await context.request.post('/api/books/manual', { data: { title: `Mobile Edit ${Date.now()}`, authors: ['Mobile Author'], isbn: null } })
  expect(added.ok()).toBe(true)
  const book = await added.json()
  await page.goto(`/library/${book.id}`)
  await page.getByRole('button', { name: 'Edit book', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Edit book', exact: true })
  await dialog.locator('input[type="file"]').setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: png })
  await expect(dialog.getByAltText('Cover preview')).toBeVisible()
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect((await (await context.request.get(`/api/books/${book.id}`)).json()).coverPath).toMatch(/^covers\/manual\//)
  await page.getByRole('button', { name: 'Edit book', exact: true }).click()
  await dialog.getByRole('button', { name: 'Remove cover', exact: true }).click()
  await dialog.getByLabel('Title', { exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/libroo-edit-modal-mobile.png' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await dialog.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect((await (await context.request.get(`/api/books/${book.id}`)).json()).coverPath).toBeNull()
  await context.close()
})
